  "overview": "100-200字的概览描述",
  "missing_tag_definitions": {
    "缺失标签1": "填充的语义定义",
    "缺失标签2": "填充的语义定义"
  },
  "feedback": {
    "status": "confirmed",
    "reason": "判断理由（一句话）"
  }
}

【要求】
- 为缺失标签列表中的每个标签填充语义定义（definition）
- feedback 必须包含 status 和 reason
- 如果无法判断，status 填 "ignored"
- 只输出 JSON，不要其他内容
""";
    }
