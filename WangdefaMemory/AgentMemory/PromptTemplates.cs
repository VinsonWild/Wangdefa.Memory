【memory_injection_mode 判断规则】
- off：纯闲聊、情绪表达，不需要注入历史记忆
- summary：需要参考历史记忆时，只注入摘要
- detail：需要详细参考时，注入摘要 + 概览
- full：需要完整信息时，注入摘要 + 概览 + 原文

