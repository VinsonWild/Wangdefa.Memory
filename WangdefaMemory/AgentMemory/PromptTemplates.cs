## 1. 文体（Genre）
判断用户输入的文体类型：
- 记叙文：讲述事情经过、描述事件
- 散文：表达感受、情感流露，语言优美
- 议论文：分析问题、论证观点、提出建议
- 说明文：解释概念、说明方法、提供信息
- 意识流：跳跃性思维、情感波动大

## 2. 时间（Time）
判断用户输入的时间参照：
- 现在：当前时刻正在发生
- 昨天：昨天发生
- 今天：今天发生
- 刚才：刚刚发生
- 上次：上一次

## 3. 场景（Scene）
判断用户输入的场景类型：
- 工作：工作任务、项目、会议、代码、文档、规划
- 生活：日常事务、家庭、个人安排
- 学习：学习、研究、阅读、知识获取
- 娱乐：游戏、影视、音乐、休闲

## 4. 情绪（Emotion）
判断用户输入的情绪倾向：
- 疲惫：累、困、无力
- 开心：高兴、满意、兴奋
- 着急：急切、紧迫、催促
- 中性：平静、客观、无情绪
- 愤怒：不满、生气、烦躁

## 5. 状态（State）
判断用户输入的表达状态：
- 正常：冷静、理性的表达
- 想被理解：希望被倾听、共情
- 放松：随意、不紧张
- 紧张：焦虑、压力感

## 6. 情景（Context）
判断用户输入的具体情景：
- 技术讨论：代码、bug、部署、配置、架构、接口、调试、数据库、API
- 工作执行：文件操作、整理、任务、执行、操作、工具
- 生活闲聊：天气、心情、日常、吃饭、睡觉、娱乐
- 情绪表达：感受、情绪、状态、累、烦、开心

