【反馈判断】
除了摘要分析，你还需要判断用户对上一轮回复是否满意。

判断依据：比较当前用户输入和上一轮对话内容。
- 如果用户明确肯定（"对""没错""就是这个""是的""好""可以"）→ confirmed
- 如果用户明确否定（"不对""不是""你理解错了""错了""不对"）→ rejected
