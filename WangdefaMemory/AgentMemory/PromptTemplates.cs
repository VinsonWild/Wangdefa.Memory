- tag：从用户输入中提取的核心关键词，2-6个
- dimension：可选值为 内容/场景/任务/约束
- definitions：对提取的tag 做的语义描述，每个语义解释10字以内，每个tag最少2个语义解释，覆盖不同角度，输出时组合成数组形式。
- synonyms：该标签的近义词列表，2-4个，用于后续匹配
- 不需要从标签池中选择，直接根据语义生成
